//! `Invitation`: a one-time link that lets a person enrol a passkey.

#![expect(
    unreachable_pub,
    reason = "the KubeSchema derive re-emits these types inside a private module"
)]

use kube::{CustomResource, KubeSchema};
use serde::{Deserialize, Serialize};

/// A one-time enrolment link for a `User`, created by an admin (`genkanctl invite`).
///
/// The link carries `<invitation name>.<secret>`; only the SHA-256 of that token is stored. It
/// works once: redeeming deletes the object with UID and resourceVersion preconditions before
/// the passkey is stored, so exactly one of any number of concurrent redemptions succeeds. When
/// `email` is set and Genkan can send mail, Genkan generates the token, records its hash in
/// `status`, and mails the link; otherwise the admin's CLI generates it and records the hash in
/// `spec`. Expired invitations are deleted by the garbage collector.
#[expect(
    clippy::duplicated_attributes,
    reason = "repeated printcolumn arguments such as `type_ = \"string\"` are distinct columns"
)]
#[derive(CustomResource, KubeSchema, Serialize, Deserialize, Clone, Debug, PartialEq, Eq)]
#[kube(
    group = "genkan.engawahq.dev",
    version = "v1alpha1",
    kind = "Invitation",
    namespaced,
    status = "InvitationStatus",
    shortname = "gkinvite",
    category = "genkan",
    selectable = ".spec.user",
    printcolumn(name = "User", type_ = "string", json_path = ".spec.user"),
    printcolumn(name = "Email", type_ = "string", json_path = ".spec.email"),
    printcolumn(
        name = "Age",
        type_ = "date",
        json_path = ".metadata.creationTimestamp"
    ),
    doc = "A one-time passkey enrolment link for a Genkan user."
)]
#[x_kube(
    validation = Rule::new("self == oldSelf").message("an invitation's spec is immutable"),
    validation = Rule::new("has(self.email) != has(self.tokenHash)").message("set exactly one of email (Genkan mails the link) and tokenHash (the link was generated by the CLI)")
)]
#[serde(rename_all = "camelCase")]
pub struct InvitationSpec {
    /// Name of the `User` object the invitation enrols a passkey for.
    #[schemars(length(min = 1, max = 253))]
    pub user: String,
    /// Immutable UID of the original invitee. Required; a reused name is not the invitee.
    #[schemars(length(min = 1, max = 128))]
    pub user_uid: String,
    /// Address Genkan mails the link to.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[schemars(
        length(min = 3, max = 254),
        regex(
            pattern = r"^[A-Za-z0-9.!#$%&'*+/=?^_`{|}~-]+@[A-Za-z0-9](?:[A-Za-z0-9-]{0,61}[A-Za-z0-9])?(?:\.[A-Za-z0-9](?:[A-Za-z0-9-]{0,61}[A-Za-z0-9])?)+$"
        )
    )]
    pub email: Option<String>,
    /// `sha256:<hex>` of the token, when the CLI generated the link.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[schemars(regex(pattern = r"^sha256:[0-9a-f]{64}$"))]
    pub token_hash: Option<String>,
    /// Language of the email: `en`, `zh-TW` or `zh-CN`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[schemars(regex(pattern = r"^(en|zh-TW|zh-CN)$"))]
    pub language: Option<String>,
    /// When the link stops working, in Unix seconds.
    #[schemars(range(min = 0))]
    pub expires_at: i64,
}

/// What Genkan recorded when it mailed the link.
#[derive(KubeSchema, Serialize, Deserialize, Clone, Debug, Default, PartialEq, Eq)]
#[x_kube(
    validation = Rule::new("!has(oldSelf.tokenHash) || (has(self.tokenHash) && self.tokenHash == oldSelf.tokenHash)").message("a recorded token hash cannot change")
)]
#[serde(rename_all = "camelCase")]
pub struct InvitationStatus {
    /// `sha256:<hex>` of the token Genkan generated and mailed.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[schemars(regex(pattern = r"^sha256:[0-9a-f]{64}$"))]
    pub token_hash: Option<String>,
    /// When the mail was sent, in Unix seconds.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[schemars(range(min = 0))]
    pub sent_at: Option<i64>,
}
